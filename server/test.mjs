  const legacyId = randomUUID();
  await db.collection('cms_entries').insertOne({ ...input, id: legacyId, kind: 'product', slug: 'legacy-product', status: 'published' });
  const legacyBefore = await db.collection('cms_entries').findOne({ id: legacyId });
  assert.equal((await request('/entries?kind=product', { cookie: '' })).status, 400);
  assert.equal((await request('/entries/product/legacy-product', { cookie: '' })).status, 404);
  assert.equal((await request('/admin/entries?kind=product')).status, 400);
  assert.equal((await request(`/admin/entries/${legacyId}`)).status, 404);
  assert.equal((await request(`/admin/entries/${legacyId}`, { method: 'PUT', body: input })).status, 404);
  assert.equal((await request(`/admin/entries/${legacyId}`, { method: 'DELETE' })).status, 404);
