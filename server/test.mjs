  assert.match(signedIn.headers.get('set-cookie'), /SameSite=Strict/i);
  adminCookie = signedIn.headers.get('set-cookie').split(';')[0];
  assert.equal((await request('/auth/me')).data.id, adminId);
  assert.equal((await request('/admin/rebuild')).data.enabled, false);
  assert.equal((await request('/admin/rebuild', { method: 'POST', body: {} })).status, 403);
  assert.equal((await request('/admin/rebuild', { method: 'POST', body: { command: 'anything' } })).status, 400);
  const input = { kind: 'blog', title: 'Integration article', slug: 'integration-article', status: 'draft', summary: 'Database backed content', hero_title: 'Hero', hero_description: 'Description', hero_image: '/products/example.jpg', body: 'Body', sections: [{ title: 'Insight', body: 'Real content' }], features: ['Feature'], benefits: ['Benefit'], related_products: [], related_industries: [], cta_text: 'Discuss', cta_url: '#connect', seo_title: 'Integration SEO', seo_description: 'SEO description', seo_keywords: 'data', canonical_url: 'https://turbo-ai.ca/blog/integration-article', og_title: 'Share', og_description: 'Share description', og_image: '/products/example.jpg', robots: 'index,follow', author: 'Turbo AI', category: 'Perspectives', tags: [], reading_time: 0, published_at: null };
